def norm(text: str) -> str:
    """نرمال‌سازی نام شهرستان برای تطبیق: حذف پرانتز، فاصله و نیم‌فاصلهٔ اضافه."""
    text = re.sub(r"[()（）]", " ", text)
    text = text.replace("‌", "").replace("ـ", "")
    text = re.sub(r"\s+", "", text)
    return text


def status_of(cell: str) -> str | None:
    """استخراج کلید وضعیت از ابتدای سلول (ممکن است پسوند توضیحی داشته باشد)."""
    for key in ("✅", "⚠️", "⏳"):
        if cell.startswith(key):
            return key
    return None


def apply_updates() -> None:
    used: set[tuple[str, str]] = set()
    for path in sorted(UNIT_DIR.glob("09-*.md")):
        lines = path.read_text(encoding="utf-8").split("\n")
        out: list[str] = []
        counts = {"✅": 0, "⚠️": 0, "⏳": 0}
        current_province = ""  # برای قالب ۵ ستونهٔ داخل «## استان X»
        for line in lines:
            if line.startswith("## استان"):
                current_province = line.replace("##", "").split("—")[0].strip().replace("استان", "").strip()
            if line.startswith("##") and not line.startswith("## استان"):
                current_province = ""
            if line.startswith("|") and line.count("|") == 6:
                # قالب ۵ ستونه: | سمت | نام | تاریخ | منبع | وضع |
                c5 = [c.strip() for c in line.strip().strip("|").split("|")]
                st = status_of(c5[4]) if len(c5) == 5 else None
                if st and not c5[1].startswith("---"):
                    if current_province and not c5[0].startswith("---"):
                        probe = c5[0]
                        gov = probe == "استاندار" or probe.startswith("استاندار ")
                        name_probe = "" if gov else probe.replace("فرماندار", "").replace("سرپرست", "").strip()
                        found = None
                        for pool in (WAVE6, WAVE5, UPDATES):
                            for u in pool:
                                if u[0] != current_province or (u[0], u[1]) in used:
                                    continue
                                if gov:
                                    if u[1] == "-" and len(u) > 6 and u[6] == "استاندار":
                                        found = u
                                        break
                                elif norm(u[1]) and norm(u[1]) in norm(name_probe):
                                    found = u
                                    break
                            if found:
                                break
                        if found:
                            used.add((found[0], found[1]))
                            c5[1] = found[2] or "—"
                            c5[2] = found[3] or "—"
                            c5[3] = found[4] or "—"
                            c5[4] = found[5]
                            if len(found) > 6:
                                c5[0] = found[6]
                            line = "| " + " | ".join(c5) + " |"
                            st = status_of(c5[4])
                    counts[st] += 1
                out.append(line)
                continue
            if not (line.startswith("|") and line.count("|") == 8):
                out.append(line)
                continue
            cells = [c.strip() for c in line.strip().strip("|").split("|")]
            prov, unit = cells[0], cells[1]
            match = None
            for pool in (WAVE6, WAVE5, UPDATES):
                for u in pool:
                    key = (u[0], u[1])
                    if key in used or u[0] != prov:
                        continue
                    if unit == "-":
                        if u[1] == "-" and len(u) > 6 and cells[2] == u[6]:
                            match = u
                            break
                    elif norm(unit) == norm(u[1]):
                        match = u
                        break
                if match:
                    break
            if match:
                _, _, name, appointed, source, status = match[:6]
                cells[3] = name or "—"
                cells[4] = appointed or "—"
                cells[5] = source or "—"
                cells[6] = status
                if len(match) > 6:
                    cells[2] = match[6]
                used.add((match[0], match[1]))
                line = "| " + " | ".join(cells) + " |"
            st = status_of(cells[6])
            if st:
                counts[st] += 1
            out.append(line)

        # بازمحاسبهٔ بند «خلاصهٔ پوشش»: جایگزینی خط عنوان تا پایان خطوط فهرست پیوسته
        idx = next((i for i, ln in enumerate(out) if ln.startswith("## خلاصهٔ پوشش گروه")), None)
        if idx is not None:
            end = idx + 1
            while end < len(out) and out[end].startswith("- "):
                end += 1
            old_note = ""
            for ln in out[idx + 1 : end]:
                pos = ln.find("(")
                if pos != -1:
                    old_note = " " + ln[pos:].rstrip()
                    break
            letter = path.stem.split("-")[1]
            out[idx:end] = [
                f"## خلاصهٔ پوشش گروه {letter}",
                f"- {sum(counts.values())} ردیف: {counts['✅']} تأییدشده `✅` | {counts['⚠️']} متعارض/ضعیف `⚠️` | {counts['⏳']} نیازمند بررسی `⏳`{old_note}",
            ]

        path.write_text("\n".join(out), encoding="utf-8")
        print(f"{path.name}: {sum(counts.values())} ردیف (✅{counts['✅']} ⚠️{counts['⚠️']} ⏳{counts['⏳']})")

    wave6_keys = {(w[0], norm(w[1])) for w in WAVE6}
    wave5_keys = {(w[0], norm(w[1])) for w in WAVE5}
    missing = [u for u in UPDATES if (u[0], u[1]) not in used and (u[0], norm(u[1])) not in wave5_keys]
    missing += [w for w in WAVE6 if (w[0], w[1]) not in used]
    missing += [w for w in WAVE5 if (w[0], w[1]) not in used]
    if missing:
        print("\n⚠️ اعمال‌نشده (نام شهرستان در جدول فایل یافت نشد):", file=sys.stderr)
        for m in missing:
            print(f"   {m[0]} | {m[1]}", file=sys.stderr)


if __name__ == "__main__":
    apply_updates()
